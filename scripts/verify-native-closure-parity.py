#!/usr/bin/env python3
"""Compare Scala-generated native Rust closure at two source checkpoints.

Usage:
  python3 scripts/verify-native-closure-parity.py BASELINE_CRATES NEW_CRATES

Both inputs must have been generated by `scripts/native-dev.py` with the
same compiler and published dependencies, using `--recursive --check`.
Source parity is stronger than comparing Scala trait source, but is not a
replacement for executing a separately changed native runtime.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def crates(folder: Path) -> set[str]:
    return {f.name for f in folder.iterdir() if f.is_dir() and (f / "Cargo.toml").is_file()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("baseline", type=Path)
    parser.add_argument("candidate", type=Path)
    args = parser.parse_args()
    original = crates(args.baseline)
    updated = crates(args.candidate)
    if not original or original != updated:
        raise SystemExit(f"Native crate closure mismatch: missing={sorted(original - updated)}, "
                         f"extra={sorted(updated - original)}")
    files = ("Cargo.toml", "src/main.rs")
    errors = []
    for name in sorted(original):
        for rel in files:
            a = args.baseline / name / rel
            b = args.candidate / name / rel
            if not a.is_file() or not b.is_file() or a.read_bytes() != b.read_bytes():
                errors.append(f"{name}/{rel}")
    if errors:
        raise SystemExit("Native source changed: " + ", ".join(errors))
    print(f"BACKGROUND_LIFECYCLE_NATIVE_PARITY_PASS crates={len(original)} "
          f"files={len(original) * len(files)}")


if __name__ == "__main__":
    main()
